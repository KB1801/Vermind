"""
FastAPI Citation Export Router.
Exports query answers and source citations in Markdown and BibTeX formats.
"""
from fastapi import APIRouter, Form
from typing import Dict, Any, List
from backend.app.retrieval.qdrant_store import qdrant_store

router = APIRouter(prefix="/export", tags=["BibTeX & Markdown Export"])

@router.post("/markdown")
async def export_markdown_notes(query: str = Form(...), answer: str = Form(...)) -> Dict[str, Any]:
    md_content = (
        f"# VeriMind Research Synthesis\n\n"
        f"**Query:** {query}\n\n"
        f"## Answer\n{answer}\n\n"
        f"---\n*Generated by VeriMind AI Platform v2.2.0*\n"
    )
    return {"format": "markdown", "export_text": md_content}

@router.post("/bibtex")
async def export_bibtex_citations(query: str = Form(...), tenant_id: str = Form("default_tenant")) -> Dict[str, Any]:
    chunks = qdrant_store.hybrid_search(query, top_k=3, tenant_id=tenant_id)

    bibtex_entries = []
    for c in chunks:
        cid = c["chunk_id"].replace("-", "_")
        doc_id = c.get("doc_id", "VeriMindDoc")
        entry = (
            f"@article{{{cid},\n"
            f"  author = {{VeriMind Knowledge Base}},\n"
            f"  title = {{{doc_id}}},\n"
            f"  journal = {{Indexed Enterprise Memory}},\n"
            f"  year = {{2026}},\n"
            f"  note = {{{c['text'][:100]}...}}\n"
            f"}}"
        )
        bibtex_entries.append(entry)

    return {"format": "bibtex", "bibtex_str": "\n\n".join(bibtex_entries)}